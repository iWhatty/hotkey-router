// scripts/key-check-reserved-report.mjs
//
// Turns the reserved-key check's event log (written by key-check-server.mjs
// while scripts/key-check-reserved.ahk runs) into a note:
//   docs/notes/key-check-reserved-<date>.md
// For each browser and Ctrl+letter: did keydown reach the page, did the
// preventDefault binding fire, and did the browser act anyway. The latest
// press of each key per browser wins, so a partial rerun updates its rows.
//
//   node scripts/key-check-reserved-report.mjs [probe.jsonl]

import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { NOTES, PROBE_LOG } from './key-check-server.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const TABLE = JSON.parse(await readFile(join(ROOT, 'data', 'browser-hotkeys.json'), 'utf8'))
const file = process.argv[2] || PROBE_LOG
const events = (await readFile(file, 'utf8')).split('\n').filter(Boolean).map((line) => JSON.parse(line))

// "browser pass" -> key -> { observe, page: [], undone }
const results = {}
const agents = {}
let current = null
let browser = null
for (const e of events) {
  if (e.source === 'page') {
    if (e.type === 'ready') agents[e.browser] = e.userAgent
    if (current && current.open) current.page.push(e)
    continue
  }
  browser = e.browser
  if (e.type === 'press') {
    current = { key: e.key, t: e.t, page: [], open: true }
    ;(results[`${browser} ${e.pass || 'bound'}`] ||= {})[e.key] = current
  } else if (e.type === 'observe' && current) {
    current.observe = e
  } else if (e.type === 'cleanup' && current) {
    current.open = false
  } else if (e.type === 'idle' && current) {
    current.undone = e.undone
    current = null
  }
}

function signs(r) {
  const out = []
  const o = r.observe || {}
  for (const p of r.page) {
    if (p.type === 'blur') out.push('page lost focus')
    if (p.type === 'visibility' && p.state === 'hidden') out.push('tab hidden')
    if (p.type === 'pagehide') out.push('page unloaded')
    if (p.type === 'beforeprint') out.push('print started')
    if (p.type === 'resize') out.push('viewport resized')
    if (['copy', 'cut', 'paste'].includes(p.type)) out.push(`${p.type} event`)
    if (p.type === 'selection') out.push('text selected')
  }
  if (o.pageWindow === false) out.push('window closed')
  else if (o.pageTabShowing === false) out.push(`other tab in front ("${o.pageTitle}")`)
  for (const w of o.newWindows || []) out.push(`new window ${w.class} "${w.title}"`)
  if (o.frontIsOtherApp) out.push(`INTERRUPTED: another app in front (${o.frontClass} "${o.frontTitle}")`)
  else if (o.frontIsPage === false && !(o.newWindows || []).length) out.push(`front: ${o.frontClass} "${o.frontTitle}"`)
  return [...new Set(out)]
}

function verdict(r) {
  const code = `Key${r.key.slice(-1).toUpperCase()}`
  const reached = r.page.some((p) => p.type === 'keydown' && p.code === code)
  const fired = r.page.some((p) => p.type === 'fired')
  const prevented = r.page.some((p) => p.type === 'keydown-after' && p.defaultPrevented)
  const acted = signs(r)
  let v
  if (r.observe?.frontIsOtherApp) v = 'interrupted, rerun'
  else if (!reached) v = acted.length ? 'browser only' : 'page never saw it, nothing visible happened'
  else if (fired && !acted.length) v = 'page wins'
  else if (fired) v = 'both: page fired, browser acted too'
  else v = 'page saw it, binding did not fire'
  return { reached, fired, prevented, acted, v }
}

const tableRow = (b, key) => TABLE.platforms.windows.browsers[b]?.[key]
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const date = new Date(events.at(-1)?.t || Date.now()).toISOString().slice(0, 10)

const lines = [
  `# Reserved key check — ${date}, Windows, US layout`,
  '',
  'Real key presses from `scripts/key-check-reserved.ahk` into',
  '`playground/key-check-reserved.html`, where every Ctrl+letter is bound with',
  '`preventDefault: true`. Generated by `scripts/key-check-reserved-report.mjs`.',
  '',
  '- **page wins**: keydown reached the page, the binding fired, and nothing',
  '  showed the browser acting (focus stayed, no tab, window or dialog).',
  '- **browser only**: the page never saw the keydown; the browser acted.',
  '- **both**: the binding fired, but the browser acted as well.',
  '- Keys with no visible default (Undo, Redo, Paste on a page with no text',
  '  field, Mute) can show "page wins" without proving the default was stopped;',
  '  `defaultPrevented` says the binding asked.',
  '',
]
for (const [run, keys] of Object.entries(results)) {
  const [b, pass] = run.split(' ')
  lines.push(`## ${b}, ${pass === 'bound' ? 'every Ctrl+letter bound with preventDefault' : 'control: nothing bound (?bound=0)'}`, '', `- Browser: ${agents[b] || 'unknown'}`, '')
  lines.push('| Key | Table (windows) | keydown reached page | Binding fired | defaultPrevented | Browser acted | Verdict | Undone by script |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const [key, r] of Object.entries(keys)) {
    const row = tableRow(b, key)
    const x = verdict(r)
    lines.push(`| ${[key, row ? `${row.severity}: ${row.action}` : '—', x.reached ? 'yes' : 'no', x.fired ? 'yes' : 'no',
      x.prevented ? 'yes' : 'no', x.acted.join('; ') || 'nothing seen', x.v, r.undone || ''].map(cell).join(' | ')} |`)
  }
  lines.push('')
}
lines.push('## Raw events', '', 'Per press: time after the press (ms), then the event.', '')
for (const [b, keys] of Object.entries(results)) {
  for (const [key, r] of Object.entries(keys)) {
    const page = r.page.map((p) => {
      const { source, browser: _, t, focused, visible, userAgent, ...rest } = p
      return `+${p.t - r.t} ${JSON.stringify(rest)} focused=${focused} ${visible}`
    })
    const { source, browser: _, t, type, key: __, ...obs } = r.observe || {}
    lines.push(`- ${b} ${key}: ${page.join(' · ') || 'no page events'} · script: ${JSON.stringify(obs)}`)
  }
}

const out = join(NOTES, `key-check-reserved-${date}.md`)
await writeFile(out, lines.join('\n') + '\n')
console.log(`wrote ${out}`)
